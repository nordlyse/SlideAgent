export const UI = { en, tr, de, gsw, nb, sv, da, is, nl, fr, es, pt, zh, ja, hi };

const REASON_KEYS = {
  "no-chrome": "chromeMissing",
  "mic-denied": "micDenied",
  "mic-not-granted": "micNotGranted",
  "no-model": "noVosk",
};

export function htmlLang(id) {
  return HTML_LANG[id] || "en";
}

export function resolveUiLanguage(id, navigatorLanguage = "") {
  if (id && id !== "auto" && UI[id]) return id;
  const nav = String(navigatorLanguage || "").toLowerCase();
  if (nav.startsWith("de-ch") || nav.startsWith("gsw")) return "gsw";
  if (nav.startsWith("nb") || nav.startsWith("nn") || nav.startsWith("no")) return "nb";
  const prefix = nav.slice(0, 2);
  if (UI[prefix]) return prefix;
  return "en";
}

export function t(lang, key, vars = {}) {
  const id = resolveUiLanguage(lang);
  const table = UI[id] || en;
  let text = table[key] ?? en[key] ?? key;
  return String(text).replace(/\{(\w+)\}/g, (_, name) => (vars[name] == null ? `{${name}}` : String(vars[name])));
}

export function translateReason(lang, reason) {
  if (!reason) return t(lang, "failed");
  const key = REASON_KEYS[reason] || (en[reason] ? reason : null);
  return key ? t(lang, key) : String(reason);
}

